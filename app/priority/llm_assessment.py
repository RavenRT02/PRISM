import json
import math
from typing import Any

from flask import current_app

from app.priority.llm_client import get_llm_client
from app.priority.priority_score_cal import find_midpoint, calculate_priority_score


def build_assessment_prompt(description: str, references: list[dict[str, Any]] | None = None) -> str:
    """Build the user prompt for assessing an issue's factor ranges."""

    prompt = f"""
                Assess the following university facility issue.

                ISSUE DESCRIPTION:
                {description}

                Assess these three factors independently:

                1. Safety: The potential for injury or harm to people.
                2. Impact: The breadth and severity of disruption to university
                facilities, activities, or users.
                3. Urgency: How quickly the issue requires attention.

                For each factor, provide a score range from 0 to 100.
                Use lower ranges for minor issues and higher ranges for serious
                issues. Consider the actual description rather than assuming an
                issue is serious merely because of its location or scope.

                Return only a valid JSON object with this exact structure:
                {{
                    "safety_score_range": [minimum, maximum],
                    "impact_score_range": [minimum, maximum],
                    "urgency_score_range": [minimum, maximum]
                }}
            """

    if references:
        examples = []   # determine_priority_path gets full references, this selects description and score keys alone

        for reference in references:
            examples.append({
                "description": reference["description"],
                "safety_score_range": reference["safety_score_range"],
                "impact_score_range": reference["impact_score_range"],
                "urgency_score_range": reference["urgency_score_range"],
            })

        prompt += (
            "\nREFERENCE EXAMPLES FOR CALIBRATION:\n"
            + json.dumps(examples, ensure_ascii=False)
            + "\nUse these examples to help calibrate your assessment. "
              "Assess the new issue on its own merits."
        )

    return prompt



def validate_score_range(value: Any, factor_name: str) -> list[float]:
    """Validate and normalize a factor range containing two scores."""

    # value - safety or impact or urgency score list inside json generated by llm
    # validate if llm returned [min, max] scores
    if not isinstance(value, list) or len(value) != 2:
        raise ValueError(f"{factor_name} must contain exactly two numbers.")

    minimum, maximum = value

    # They should not be True/ False, must be int/float, must be finite and should be between 0 to 100 
    # why do we need to check if score is finite or int/float ? won't 0 <= score <= 100 already cover those two ?
    # int/float check to prevent str values that could raise TypeError, finite check to prevent NaN
    for score in (minimum, maximum):
        if (isinstance(score, bool)
            or not isinstance(score, (int, float))
            or not math.isfinite(score)
            or not 0 <= score <= 100):
            raise ValueError(f"{factor_name} scores must be numbers from 0 to 100.")  

    if minimum > maximum:
        raise ValueError(f"{factor_name} minimum cannot exceed its maximum.")

    return [float(minimum), float(maximum)]



def assess_issue_with_llm(description: str, references: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    """
    Ask the configured LLM for factor ranges, validate them,
    and calculate midpoint scores and the initial priority.

    Does not save anything to the database.
    """

    if not description or not description.strip():
        raise ValueError("Issue description cannot be empty.")

    # no need to check for path since this only happens if the path is to reach llm
    client = get_llm_client()

    prompt = build_assessment_prompt(description, references)

    response = client.chat.completions.create(
        model=current_app.config["LLM_MODEL"],
        messages=[
            {
                "role": "system",
                "content": (
                    "You are a consistent issue-assessment assistant. "
                    "Return only a valid JSON object matching the requested schema."
                    "Do not invent extra fields."
                )
            },

            {
                "role": "user",
                "content": prompt,
            }
        ],
        response_format={"type": "json_object"},
    )

    content = response.choices[0].message.content

    if not content:
        raise ValueError("The LLM returned an empty response.")

    # validates json syntax
    try:
        result = json.loads(content)
    except json.JSONDecodeError as exc:
        raise ValueError("The LLM returned invalid JSON.") from exc

    # checks top-level datatype (checks if it is actually python dict)
    if not isinstance(result, dict):
        raise ValueError("The LLM response must be a JSON object.")

    required_keys = {"safety_score_range", "impact_score_range", "urgency_score_range"}

    # using set because it is unordered not to filter duplicates, taking keys given by llm and comparing with required keys
    if set(result.keys()) != required_keys:
        raise ValueError("The LLM response contains missing or unexpected fields.")

    safety_range = validate_score_range(result["safety_score_range"], "Safety")
    impact_range = validate_score_range(result["impact_score_range"], "Impact")
    urgency_range = validate_score_range(result["urgency_score_range"], "Urgency")

    safety, impact, urgency = find_midpoint(safety_range, impact_range, urgency_range)

    priority_score, priority_level = calculate_priority_score(safety, impact, urgency)

    return {
        "safety_score_range": safety_range,
        "impact_score_range": impact_range,
        "urgency_score_range": urgency_range,
        "safety_score": safety,
        "impact_score": impact,
        "urgency_score": urgency,
        "priority_score": priority_score,
        "priority_level": priority_level,
    }
